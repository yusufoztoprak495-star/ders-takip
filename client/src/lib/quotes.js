// --- Söz seçimi: karıştırılmış deste ---
// Sözler bir iskambil destesi gibi karıştırılır ve sırayla çekilir: her açılışta ve "Başka söz"e her
// basışta desteden yeni bir söz gelir. Deste bitmeden hiçbir söz tekrar etmez; bitince yeniden karıştırılır
// (yeni destenin ilk sözü, bir önceki destenin son sözü olamaz). Deste tarayıcıda saklanır (Home.jsx).

// 0..count-1 sayılarının karışık sırası (Fisher–Yates: her sıralama eşit olasılıkla çıkar)
export function shuffledOrder(count, rng = Math.random) {
  const order = [...Array(count).keys()];
  for (let i = count - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order;
}

// Saklanan deste kullanılabilir mi? (söz listesi büyüdüyse ya da kayıt bozulduysa baştan kurulur)
function isValidDeck(deck, count) {
  return (
    deck !== null &&
    typeof deck === "object" &&
    Array.isArray(deck.order) &&
    deck.order.length === count &&
    Number.isInteger(deck.pos) &&
    deck.pos >= 0 &&
    deck.pos <= count &&
    deck.order.every((i) => Number.isInteger(i) && i >= 0 && i < count) &&
    new Set(deck.order).size === count
  );
}

// Desteden bir söz çeker. { index: söz sırası, deck: saklanacak yeni deste } döner.
export function drawQuote(deck, count, rng = Math.random) {
  let current = isValidDeck(deck, count) ? { order: [...deck.order], pos: deck.pos } : null;
  if (!current || current.pos >= count) {
    const previousLast = current ? current.order[count - 1] : null;
    const order = shuffledOrder(count, rng);
    if (count > 1 && order[0] === previousLast) [order[0], order[1]] = [order[1], order[0]];
    current = { order, pos: 0 };
  }
  const index = current.order[current.pos];
  current.pos += 1;
  return { index, deck: current };
}
